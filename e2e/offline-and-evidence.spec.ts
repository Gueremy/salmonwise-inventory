import { test, expect } from "@playwright/test";

test("login, evidencia reversible, recarga offline y recepción de lote nuevo", async ({ page, context }, info) => {
  const lotNumber = `LOTE-${info.project.name}-${Date.now()}`;
  const lostResponse = `Respuesta perdida ${info.project.name}-${Date.now()}`;
  await page.goto("/");
  await page.getByLabel("Correo electronico").fill("browser@example.cl");
  await page.getByLabel("Contrasena").fill("BrowserTest123!");
  await page.getByRole("button", { name: "Ingresar", exact: true }).click();
  await expect(page).toHaveURL(/operario/);
  await expect(page.getByText("Operaria privada de prueba")).toBeVisible();
  const writes: string[] = [];
  page.on("request", (request) => { if (["POST", "PUT", "PATCH", "DELETE"].includes(request.method())) writes.push(request.url()); });
  await page.getByRole("button", { name: "Proteger datos para capturas" }).click();
  await expect(page.getByText("Operaria privada de prueba")).toHaveCount(0);
  await expect(page.getByText("Insumo privado de prueba", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("evidence-mode.png"), fullPage: true });
  await page.getByRole("button", { name: /Mostrar datos/ }).click();
  await expect(page.getByText("Operaria privada de prueba")).toBeVisible();
  expect(writes).toEqual([]);
  await page.getByRole("button", { name: /Preparar dispositivo/ }).click();
  await expect(page.getByText(/Listo sin conexión hasta/)).toBeVisible();
  await page.evaluate(() => navigator.serviceWorker.ready);
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByText("P0001", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Registrar Entrada", exact: true }).click();
  await page.getByLabel("Ubicación de destino").click();
  await page.getByRole("option", { name: "P0002" }).click();
  await page.getByLabel("Ítem", { exact: true }).click();
  await page.getByRole("option", { name: /Insumo privado de prueba/ }).click();
  await page.getByLabel("Cantidad", { exact: true }).fill("2");
  await page.getByLabel("Recibir un lote nuevo").check();
  await page.getByLabel("Número de lote").fill(lotNumber);
  await page.getByLabel("Razón social del proveedor").fill("Proveedor de prueba");
  await page.getByLabel("RUT del proveedor").fill("76123456-0");
  await page.getByRole("button", { name: "Registrar", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Registrar Salida", exact: true }).click();
  await page.getByLabel("Ubicación de origen").click();
  await page.getByRole("option", { name: "P0001" }).click();
  await page.getByLabel("Ítem", { exact: true }).click();
  await page.getByRole("option", { name: /Insumo privado de prueba/ }).click();
  await page.getByLabel("Lote (opcional)").click();
  await page.getByRole("option", { name: "LOTE-E2E", exact: true }).click();
  await page.getByLabel("Cantidad", { exact: true }).fill("5");
  await page.getByRole("button", { name: "Registrar", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Traslado", exact: true }).click();
  await page.getByLabel("Ubicación de origen").click();
  await page.getByRole("option", { name: "P0001" }).click();
  await page.getByLabel("Ubicación de destino").click();
  await page.getByRole("option", { name: "P0002" }).click();
  await page.getByLabel("Ítem", { exact: true }).click();
  await page.getByRole("option", { name: /Insumo privado de prueba/ }).click();
  await page.getByLabel("Lote (opcional)").click();
  await page.getByRole("option", { name: "LOTE-E2E", exact: true }).click();
  await page.getByLabel("Cantidad", { exact: true }).fill("3");
  await page.getByRole("button", { name: "Registrar", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.reload();
  await expect(page.getByText(/3 Pendientes/)).toBeVisible();
  await context.setOffline(false);
  await expect(page.getByText(/3 Pendientes/)).toHaveCount(0, { timeout: 20000 });
  await page.getByRole("button", { name: "Registrar Entrada", exact: true }).click();
  await page.getByLabel("Ubicación de destino").click();
  await page.getByRole("option", { name: "P0002" }).click();
  await page.getByLabel("Ítem", { exact: true }).click();
  await page.getByRole("option", { name: /Insumo privado de prueba/ }).click();
  await page.getByLabel("Cantidad", { exact: true }).fill("1");
  await page.getByLabel("Observaciones").fill(lostResponse);
  await page.route("**/api/v2/movimientos/solicitudes", async (route) => {
    await route.fetch(); // The real backend commits; only the response to the browser is lost.
    await route.abort("failed");
  });
  await page.getByRole("button", { name: "Registrar", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.unroute("**/api/v2/movimientos/solicitudes");
  await expect(page.getByText(/1 Pendiente/)).toBeVisible({ timeout: 10000 });
  await page.getByRole("button", { name: /1 Pendiente/ }).click();
  await expect(page.getByText(/1 Pendiente/)).toHaveCount(0, { timeout: 20000 });
  const ledger = await page.evaluate(async () => {
    const token = localStorage.getItem("axious.accessToken");
    return (await fetch("http://localhost:8000/api/v2/movimientos/", { headers: { Authorization: `Bearer ${token}` } })).json();
  });
  expect(ledger.items.filter((item: {observaciones?: string}) => item.observaciones === lostResponse)).toHaveLength(1);
  await page.goto("/movements");
  await page.getByPlaceholder("Buscar producto, lote, operario o container").fill(lotNumber);
  await expect(page.getByRole("cell", { name: lotNumber, exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "Insumo privado de prueba", exact: true })).toBeVisible();
});
